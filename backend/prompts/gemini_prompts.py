def build_curation_user_prompt(
    facts_and_clues: dict[str, Any],
    qa_pairs: list[dict[str, Any]],
) -> str:
    payload = {
        "visual_facts_and_clues": facts_and_clues,
        "user_interview_answers": qa_pairs,
    }

    return (
        "아래 사진 단서와 사용자의 실제 답변을 이용해 "
        "추억 노트를 작성하세요.\n\n"
        + json.dumps(
            payload,
            ensure_ascii=False,
            indent=2,
        )
    )


